#!/usr/bin/env node
// test-scrub — the attribution scrubber removes what O09 forbids and nothing else (K006).
//
//   node tools/test-scrub.mjs        exit 0 = every case held

import { scrub, target, footerLines, rerunnable, sweepSince, sweep, SWEEP_MARGIN_MS, SWEEP_FALLBACK_MS } from '../.harness/tools/scrub.mjs';

let n = 0;
const eq = (got, want, what) => {
  n++;
  if (got !== want) { console.log(`test-scrub: FAIL ${n}. ${what}\n--- got ---\n${got}\n--- want ---\n${want}`); process.exit(1); }
  console.log(`test-scrub: ok ${n}. ${what}`);
};

// catches: the footers and links the platform and sessions add
eq(scrub('Fixes the build.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'), 'Fixes the build.\n', 'a "Generated by" footer and its rule go');
eq(scrub('Summary.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01ABC\n'), 'Summary.\n', '"Generated with" line and a bare session link go');
eq(scrub('_Requested by **Jahjah** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_2)_\n\nBody.'), '_Requested by **Jahjah**_\n\nBody.', 'a thread link goes with its dangling separator; the rest of the line stays');
eq(scrub('Done.\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_1\n'), 'Done.\n', 'co-author and session lines go');
eq(scrub('See https://claude.ai/code/session_1 for the run.'), 'See for the run.', 'an inline link goes, the sentence stays');
eq(scrub('Done.\r\n\r\n---\r\n_Generated by [Claude Code](https://claude.ai/code)_\r\n'), 'Done.\r\n', 'CRLF bodies keep CRLF');
eq(scrub('a\n\n<https://www.claude.ai/x>\n\nb'), 'a\n\nb', 'an autolink and the blank lines around it collapse');

eq(JSON.stringify(footerLines('a\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n```\nGenerated by Claude Code\n```')), '["_Generated by [Claude Code](https://claude.ai/code)_"]', 'footerLines lists the footer outside code and ignores a quoted one');

eq(JSON.stringify(rerunnable([{ id: 1, name: 'harness-guard', conclusion: 'failure' }, { id: 2, name: 'harness-guard', conclusion: 'success' }, { id: 3, name: 'ci', conclusion: 'failure' }, { id: 4, name: 'hands-check', conclusion: 'failure' }])), '[1,4]', 'only failed runs of the footer-gating checks are started again');

// accepts: correct text is returned unchanged, byte for byte
const keep = [
  'Plain body.\n\n---\n\nA section after a rule.\n',
  'Uses the Anthropic API via claude-sonnet; docs at https://docs.anthropic.com/claude.\n',
  'Written with care by Claude the colleague, not a footer.',
  '```text\nGenerated by Claude Code\nhttps://claude.ai/code/x\n```\n',
  'notclaude.ai.example.com and https://example.com/claude.ai stay',
  'https://claude.ai.example.com/x and https://notclaude.ai/y are other hosts',
  '',
  'Use `https://claude.ai/code` in the config; `x` stays code.',
  '<a href="https://claude.ai/x">link</a> is markup',
  '| a | https://example.com |',
  'Call foo() and bar(1).',
  'Two  spaces  stay.',
  'This was not generated by Claude Code, a person wrote it.',
  'Co-authored-by: Claude Monet <claude@example.com>',
];
for (const k of keep) eq(scrub(k), k, `unchanged: ${JSON.stringify(k.slice(0, 40))}`);
eq(scrub(null), null, 'a null body stays null');

eq(scrub('Cells: | [run](https://claude.ai/x) | next |'), 'Cells: | | next |', 'a link inside a table cell goes; the pipes stay');
eq(scrub('Report (https://claude.ai/code/session_1) attached.'), 'Report attached.', 'parentheses that held only the link go with it');

// linear time on hostile input (a public repo lets anyone post)
for (const [what, body] of [['50k brackets then a link', `${'['.repeat(50000)} https://claude.ai/x`], ['a link then 50k spaces', `x https://claude.ai/a${' '.repeat(50000)}y`], ['50k dots', `https://${'a.'.repeat(25000)}`]]) {
  const t0 = performance.now(); scrub(body); const ms = performance.now() - t0;
  n++; if (ms > 1000) { console.log(`test-scrub: FAIL ${n}. ${what} took ${ms.toFixed(0)} ms`); process.exit(1); }
  console.log(`test-scrub: ok ${n}. ${what}: ${ms.toFixed(0)} ms`);
}

// the event → endpoint map
const repo = { full_name: 'o/r' };
eq(target('issues', { repository: repo, issue: { number: 3 } })?.path, '/repos/o/r/issues/3', 'issue body');
eq(target('pull_request_target', { repository: repo, pull_request: { number: 4 } })?.path, '/repos/o/r/pulls/4', 'PR body');
eq(target('pull_request', { repository: repo, pull_request: { number: 4 } })?.path, '/repos/o/r/pulls/4', 'PR body on pull_request (K030)');
eq(target('issue_comment', { repository: repo, issue: { number: 4 }, comment: { id: 9 } })?.path, '/repos/o/r/issues/comments/9', 'issue or PR comment');
eq(target('pull_request_review_comment', { repository: repo, comment: { id: 8 } })?.path, '/repos/o/r/pulls/comments/8', 'review comment');
eq(target('pull_request_review', { repository: repo, pull_request: { number: 4 }, review: { id: 7 } })?.method, 'PUT', 'review body is saved with PUT');
eq(target('push', { repository: repo }), null, 'other events touch nothing');

// --- one run per burst (K059): where the sweep starts, and what it cleans ---------------------------------
const NOW = Date.parse('2026-11-21T18:00:00Z');
const at = (iso) => new Date(Date.parse(iso) - SWEEP_MARGIN_MS).toISOString();
const r = (id, created_at, conclusion, extra = {}) => ({ id, created_at, conclusion, event: 'issue_comment', ...extra });
eq(sweepSince([r(5, '2026-11-21T17:00:00Z', 'success'), r(7, '2026-11-21T17:30:00Z', 'success'), r(9, '2026-11-21T17:50:00Z', 'success')], { repo: 'o/r', currentId: 9, now: NOW }), at('2026-11-21T17:30:00Z'),
  'the sweep starts at the newest earlier green run, less the margin (never at its own run or a later one)');
eq(sweepSince([r(5, '2026-11-21T17:00:00Z', 'success'), r(6, '2026-11-21T17:20:00Z', 'cancelled'), r(7, '2026-11-21T17:30:00Z', 'failure'), r(8, '2026-11-21T17:40:00Z', 'skipped')], { repo: 'o/r', currentId: 9, now: NOW }), at('2026-11-21T17:00:00Z'),
  'a cancelled (dropped), failed or skipped run covered nothing: the window reaches back to the last green one');
eq(sweepSince([r(5, '2026-11-21T17:00:00Z', 'success'), r(7, '2026-11-21T17:30:00Z', 'success', { event: 'pull_request', head_repository: { full_name: 'fork/r' } }), r(8, '2026-11-21T17:40:00Z', 'success', { actor: { login: 'dependabot[bot]' } })], { repo: 'o/r', currentId: 9, now: NOW }), at('2026-11-21T17:00:00Z'),
  'a fork\'s or Dependabot\'s run (read-only, its own group) swept nothing and does not count');
eq(sweepSince([r(5, '2026-11-21T17:00:00Z', 'success'), r(7, '2026-11-21T17:30:00Z', 'success')], { repo: 'o/r', currentId: 9, now: NOW, notBefore: '2026-11-21T17:10:00Z' }), at('2026-11-21T17:30:00Z'),
  'a green run after the workflow file last changed anchors the window');
eq(sweepSince([r(5, '2026-11-21T17:00:00Z', 'success'), r(7, '2026-11-21T17:30:00Z', 'success')], { repo: 'o/r', currentId: 9, now: NOW, notBefore: '2026-11-21T17:45:00Z' }), new Date(NOW - SWEEP_FALLBACK_MS).toISOString(),
  'the first run after a kit update sweeps the last day: older green runs ran the old file, which did not sweep, so runs cancelled before the update lose nothing');
eq(sweepSince([r(7, '2026-11-21T17:30:00Z', 'success')], { repo: 'o/r', currentId: 9, now: NOW, notBefore: new Date(8.64e15).toISOString() }), new Date(NOW - SWEEP_FALLBACK_MS).toISOString(),
  'an unknown change date trusts no earlier run: the last day');
eq(sweepSince([], { repo: 'o/r', currentId: 9, now: NOW }), new Date(NOW - SWEEP_FALLBACK_MS).toISOString(), 'no green run (or an unreadable list): the last day');
eq(sweepSince([r(5, '2026-11-01T00:00:00Z', 'success')], { repo: 'o/r', currentId: 9, now: NOW }), new Date(NOW - SWEEP_FALLBACK_MS).toISOString(), 'never further back than the last day');

{
  const FOOT = 'Body.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';
  const db = {
    '/repos/o/r/issues/1': { number: 1, body: 'clean' },
    '/repos/o/r/issues/2': { number: 2, body: FOOT, pull_request: {} },
    '/repos/o/r/issues/comments/10': { id: 10, body: FOOT },
    '/repos/o/r/issues/comments/11': { id: 11, body: 'fine' },
    '/repos/o/r/pulls/comments/20': { id: 20, body: FOOT },
    '/repos/o/r/pulls/2/reviews/30': { id: 30, body: FOOT },
    '/repos/o/r/pulls/2': { number: 2, head: { sha: 'abc' } },
  };
  const calls = [];
  let readOnly = false;
  const get = async (method, path, body) => {
    calls.push(`${method} ${path.replace(/\?.*/, '')}`);
    const base = path.replace(/\?.*/, '');
    if (method === 'GET' && base === '/repos/o/r/issues') return [db['/repos/o/r/issues/1'], db['/repos/o/r/issues/2']];
    if (method === 'GET' && base === '/repos/o/r/issues/comments') return [db['/repos/o/r/issues/comments/10'], db['/repos/o/r/issues/comments/11']];
    if (method === 'GET' && base === '/repos/o/r/pulls/comments') return [db['/repos/o/r/pulls/comments/20']];
    if (method === 'GET' && base === '/repos/o/r/pulls/2/reviews') return [db['/repos/o/r/pulls/2/reviews/30']];
    if (method === 'GET' && base === '/repos/o/r/actions/runs') return { workflow_runs: [{ id: 99, name: 'harness-guard', conclusion: 'failure' }] };
    if (method === 'GET') return db[base];
    if (readOnly && (method === 'PATCH' || method === 'PUT')) { const e = new Error('403'); e.status = 403; throw e; }
    if (method === 'PATCH' || method === 'PUT') { db[base] = { ...db[base], body: body.body }; return db[base]; }
    return {};
  };
  const saved = await sweep('o/r', '2026-11-21T17:00:00Z', get);
  eq(JSON.stringify(saved.sort()), JSON.stringify(['/repos/o/r/issues/2', '/repos/o/r/issues/comments/10', '/repos/o/r/pulls/2/reviews/30', '/repos/o/r/pulls/comments/20']),
    'the sweep cleans every body in the window: a pull request\'s description, a comment, a review comment and a review');
  eq(db['/repos/o/r/issues/comments/10'].body, 'Body.\n', 'a swept body is saved without its footer');
  eq(String(calls.some((c) => c === 'PATCH /repos/o/r/issues/1' || c === 'PATCH /repos/o/r/issues/comments/11')), 'false', 'a clean body is never written');
  eq(String(calls.includes('PUT /repos/o/r/pulls/2/reviews/30') && calls.includes('POST /repos/o/r/actions/runs/99/rerun-failed-jobs')), 'true', 'a review is saved with PUT, and a cleaned pull request description starts its failed guard again (K044)');
  eq(JSON.stringify((await sweep('o/r', '2026-11-21T17:00:00Z', get))), '[]', 'a second sweep over the same window writes nothing');
  db['/repos/o/r/issues/comments/11'].body = FOOT; readOnly = true;
  eq(JSON.stringify(await sweep('o/r', '2026-11-21T17:00:00Z', get)), '[]', 'a read-only token leaves the body with a warning; the sweep does not fail');
  // a body deleted after the listing is a warning, not a red run
  db['/repos/o/r/issues/comments/11'] = undefined;
  const get404 = async (m, p, b) => { if (m === 'GET' && p === '/repos/o/r/issues/comments/11') { const e = new Error('404'); e.status = 404; throw e; } return get(m, p, b); };
  const listed11 = async (m, p, b) => (m === 'GET' && p.startsWith('/repos/o/r/issues/comments?') ? [{ id: 11, body: FOOT }] : m === 'GET' && /\/(issues|pulls\/comments)\?/.test(p) ? [] : get404(m, p, b));
  eq(JSON.stringify(await sweep('o/r', '2026-11-21T17:00:00Z', listed11)), '[]', 'a body deleted between the listing and the save is a warning; the sweep goes on');
  // a listing cut at the page cap fails the run, so the next sweep starts from the last green run again
  const full = Array.from({ length: 100 }, (_, i) => ({ id: 1000 + i, body: 'fine' }));
  const many = async (m, p, b) => (m === 'GET' && p.startsWith('/repos/o/r/issues/comments?') ? full : m === 'GET' && /\/(issues|pulls\/comments)\?/.test(p) ? [] : get(m, p, b));
  let capped = null; try { await sweep('o/r', '2026-11-21T17:00:00Z', many); } catch (e) { capped = e; }
  eq(String(!!capped?.capped), 'true', 'a listing longer than the page cap fails the run (only a green run moves the window)');
  // a later edit between the listing and the save is never overwritten: the body is read again first
  readOnly = false;
  const stale = { id: 12, body: FOOT };
  db['/repos/o/r/issues/comments/12'] = { id: 12, body: 'edited since, no footer' };
  const get2 = async (m, p, b) => (m === 'GET' && p.startsWith('/repos/o/r/issues/comments?') ? [stale] : m === 'GET' && /\/(issues|pulls\/comments)\?/.test(p) ? [] : get(m, p, b));
  eq(JSON.stringify(await sweep('o/r', '2026-11-21T17:00:00Z', get2)) + db['/repos/o/r/issues/comments/12'].body, '[]edited since, no footer', 'a body edited after the listing is read again and left as it now is');
}

console.log(`test-scrub: OK · ${n} checks`);
